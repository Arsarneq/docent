//! Generates the desktop crate's Win32 bindings.
//!
//! `cargo run --locked` (from this directory, or with `--manifest-path` from
//! anywhere) writes `../../src/capture/win32_bindings.rs` from `filter.txt`
//! with windows-bindgen: the flat layout, and `_Impl` traits for the provider
//! interfaces the corpus fixture implements.
//!
//! `cargo run --locked -- --check` regenerates into a temporary file, compares
//! the bytes with the committed file, checks that the desktop crate's
//! `windows-core` pin and this crate's `windows-bindgen` pin sit on one
//! `0.<minor>` version line, and exits 1 naming what drifted. `-- --out <path>`
//! names another file in place of the committed one: the default mode writes
//! it, `--check` compares against it. Every output opens with the banner below.
//!
//! windows-bindgen formats its output through the `rustfmt` on PATH, so the
//! committed bytes depend on the toolchain (CI's lint job uses `stable`) and
//! on rustfmt's configuration. The generator pins the configuration by running
//! with this directory as its working directory, where the committed
//! `rustfmt.toml` ends rustfmt's configuration search.

use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

/// The committed output, relative to this crate's manifest directory.
const BINDINGS: &str = "../../src/capture/win32_bindings.rs";
/// The first lines of every output file, so a reader landing in it sees what
/// it is; part of the bytes the check compares.
const BANNER: &str = "\
// Generated by tools/bindgen (windows-bindgen, pinned in its Cargo.toml) from
// tools/bindgen/filter.txt — never hand-edit. Regenerate under CI's toolchain:
// `rustup update stable`, then
// `cargo +stable run --locked --manifest-path packages/desktop/src-tauri/tools/bindgen/Cargo.toml`.
";
/// The desktop crate's manifest, relative to this crate's manifest directory.
const APP_MANIFEST: &str = "../../Cargo.toml";
/// The provider interfaces the corpus fixture implements: the only ones whose
/// `_Impl` traits are generated.
const IMPLEMENT: &[&str] = &[
    "Windows.Win32.IRawElementProviderSimple",
    "Windows.Win32.IRawElementProviderFragment",
    "Windows.Win32.IRawElementProviderFragmentRoot",
    "Windows.Win32.IRawElementProviderHwndOverride",
];

fn main() -> ExitCode {
    let mut check = false;
    let mut out_override: Option<PathBuf> = None;
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--check" => check = true,
            "--out" => match args.next() {
                Some(p) => out_override = Some(PathBuf::from(p)),
                None => return usage("--out needs a path"),
            },
            other => return usage(&format!("unknown argument `{other}`")),
        }
    }

    let here = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let committed = match out_override {
        Some(p) => match std::path::absolute(&p) {
            Ok(p) => p,
            Err(e) => return fail(&format!("{}: {e}", p.display())),
        },
        None => here.join(BINDINGS),
    };
    // rustfmt resolves its configuration from the working directory chain;
    // this directory holds the committed `rustfmt.toml`, so every run — from
    // any caller, on any machine — resolves the same configuration.
    if let Err(e) = std::env::set_current_dir(&here) {
        return fail(&format!("cannot enter {}: {e}", here.display()));
    }
    let filter = here.join("filter.txt");

    if !check {
        generate(&filter, &committed);
        println!("wrote {}", committed.display());
        return ExitCode::SUCCESS;
    }

    let mut failures = Vec::new();
    let fresh =
        std::env::temp_dir().join(format!("docent-win32-bindings-{}.rs", std::process::id()));
    generate(&filter, &fresh);
    let fresh_bytes = std::fs::read(&fresh).expect("read the regenerated bindings");
    let _ = std::fs::remove_file(&fresh);
    match std::fs::read(&committed) {
        Ok(bytes) if bytes == fresh_bytes => {}
        Ok(_) => failures.push(format!(
            "{} differs from a fresh run of the generator",
            committed.display()
        )),
        Err(e) => failures.push(format!("{}: {e}", committed.display())),
    }

    let own = pinned_version(&here.join("Cargo.toml"), "windows-bindgen");
    let app = pinned_version(&here.join(APP_MANIFEST), "windows-core");
    match (
        own.as_deref().and_then(minor_line),
        app.as_deref().and_then(minor_line),
    ) {
        (Some(o), Some(a)) if o == a => {}
        _ => failures.push(format!(
            "version pins are not on one line: windows-bindgen {} (this crate) vs windows-core {} (desktop crate); each pin is read from a `name = \"=x.y.z\"` line of its own",
            own.as_deref().unwrap_or("<no pin line read>"),
            app.as_deref().unwrap_or("<no pin line read>")
        )),
    }

    let rustfmt = rustfmt_version();
    if failures.is_empty() {
        println!("win32 bindings fresh; version pins on one line (formatted with {rustfmt})");
        return ExitCode::SUCCESS;
    }
    for f in &failures {
        eprintln!("error: {f}");
    }
    eprintln!("formatted with: {rustfmt}");
    eprintln!(
        "fix: regenerate under CI's toolchain — `rustup update stable`, then \
         `cargo +stable run --locked --manifest-path packages/desktop/src-tauri/tools/bindgen/Cargo.toml` \
         — and commit the result; keep windows-core and windows-bindgen on one 0.<minor> version line (a moved windows-bindgen pin also refreshes this crate's Cargo.lock: `cargo update -p windows-bindgen` here)"
    );
    ExitCode::FAILURE
}

fn generate(filter: &Path, out: &Path) {
    let mut args: Vec<String> = vec![
        "--out".into(),
        out.to_string_lossy().into_owned(),
        "--filter-file".into(),
        filter.to_string_lossy().into_owned(),
        "--flat".into(),
        "--implement".into(),
    ];
    args.extend(IMPLEMENT.iter().map(|s| s.to_string()));
    windows_bindgen::bindgen(args);
    let body = std::fs::read(out).expect("read the generator's output");
    let mut file = BANNER.as_bytes().to_vec();
    file.extend_from_slice(&body);
    std::fs::write(out, file).expect("write the bindings with their banner");
}

/// The `=x.y.z` requirement a manifest states for `name` on a line of its own
/// (`name = "=x.y.z"`), or None when the manifest states none.
fn pinned_version(manifest: &Path, name: &str) -> Option<String> {
    let text = std::fs::read_to_string(manifest).ok()?;
    text.lines().find_map(|line| {
        let rest = line.trim_start().strip_prefix(name)?;
        let rest = rest.trim_start().strip_prefix('=')?.trim_start();
        let quoted = rest.strip_prefix('"')?.strip_prefix('=')?;
        let end = quoted.find('"')?;
        Some(quoted[..end].to_string())
    })
}

/// `"0.100.0"` → `"0.100"`; None unless the version has three dotted parts.
fn minor_line(version: &str) -> Option<&str> {
    let mut parts = version.splitn(3, '.');
    let major = parts.next()?;
    let minor = parts.next()?;
    parts.next()?;
    Some(&version[..major.len() + 1 + minor.len()])
}

/// What `rustfmt --version` on PATH reports — the formatter the bytes came from.
fn rustfmt_version() -> String {
    Command::new("rustfmt")
        .arg("--version")
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .unwrap_or_else(|| "rustfmt not found on PATH".to_string())
}

fn usage(why: &str) -> ExitCode {
    eprintln!("error: {why}\nusage: cargo run --locked -- [--check] [--out <path>]");
    ExitCode::FAILURE
}

fn fail(why: &str) -> ExitCode {
    eprintln!("error: {why}");
    ExitCode::FAILURE
}
